#!/usr/bin/env node
// Sinh bảng định tuyến lệnh WebSocket và validator envelope của gateway realtime (F090 T008) từ AsyncAPI
// specs/asyncapi/eduworld-realtime.v1.yaml: mỗi operation `receive` khai báo `x-routing` (`module`, `room_input`).
//   - src/backend/modules/realtime/internal/router/routes_gen.go     (type → module, kiểu chuyển tiếp)
//   - src/backend/modules/realtime/internal/protocol/validate_gen.go  (JSON Schema draft-07 của từng lệnh client)
// Chạy:  node scripts/realtime/gen-routes.mjs          (ghi file)
//        node scripts/realtime/gen-routes.mjs --check  (CI: exit 1 nếu file sinh lệch spec)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const yaml = require('js-yaml');
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const SPEC = path.join(repo, 'specs/asyncapi/eduworld-realtime.v1.yaml');
const ROUTES = path.join(repo, 'src/backend/modules/realtime/internal/router/routes_gen.go');
const VALIDATE = path.join(repo, 'src/backend/modules/realtime/internal/protocol/validate_gen.go');
const MODULES = new Set(['realtime', 'chat', 'competition', 'game', 'learning', 'identity']);
const TYPE_RE = /^[a-z_]+([.][a-z_]+){1,2}$/; // chat.sync có 2 đoạn (OQ F090-1: lệch pattern của ClientEnvelope)

const doc = yaml.load(fs.readFileSync(SPEC, 'utf8'));
const errors = [];
const resolve = (ref) => ref.replace(/^#\//, '').split('/').reduce((o, k) => o?.[k], doc);

// type → {module, kind}
const routes = new Map();
const messages = new Map(); // type → payload schema
for (const [opId, op] of Object.entries(doc.operations ?? {})) {
  if (op.action !== 'receive') continue;
  const r = op['x-routing'];
  if (!r || !MODULES.has(r.module)) { errors.push(`${opId}: thiếu x-routing.module hợp lệ`); continue; }
  const roomInput = new Set(r.room_input ?? []);
  for (const ref of op.messages ?? []) {
    let m = resolve(ref.$ref);
    if (m?.$ref) m = resolve(m.$ref);
    const type = m?.name;
    if (!type || !TYPE_RE.test(type)) { errors.push(`${opId}: message ${ref.$ref} không có name hợp lệ`); continue; }
    if (routes.has(type)) { errors.push(`${type}: khai báo ở nhiều operation receive`); continue; }
    const kind = r.module === 'realtime' ? 'KindLocal' : roomInput.delete(type) ? 'KindRoomInput' : 'KindRequest';
    routes.set(type, { module: r.module, kind });
    messages.set(type, m.payload);
  }
  for (const t of roomInput) errors.push(`${opId}: room_input ${t} không có trong messages`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

// Bundle: components.schemas → $defs; bỏ mô tả (không ảnh hưởng validate) để file sinh gọn.
const DROP = new Set(['description', 'summary', 'title', 'examples', 'example']);
const clean = (v) => {
  if (Array.isArray(v)) return v.map(clean);
  if (v && typeof v === 'object') {
    const o = {};
    for (const k of Object.keys(v).sort()) {
      if (DROP.has(k) || k.startsWith('x-')) continue;
      o[k] = k === '$ref' ? v[k].replace('#/components/schemas/', '#/$defs/') : clean(v[k]);
    }
    return o;
  }
  return v;
};
const defs = {};
for (const k of Object.keys(doc.components.schemas).sort()) defs[k] = clean(doc.components.schemas[k]);
const types = [...routes.keys()].sort();
for (const t of types) defs[`msg.${t}`] = clean(messages.get(t));
// AsyncAPI 3.0 Schema Object = superset of JSON Schema draft-07 (tuple items, additionalItems).
const bundle = { $schema: 'http://json-schema.org/draft-07/schema#', $defs: defs };

const header = '// Code generated by scripts/realtime/gen-routes.mjs from specs/asyncapi/eduworld-realtime.v1.yaml. DO NOT EDIT.\n\n';
const pad = Math.max(...types.map((t) => t.length)) + 4;
const routesGo = header + `package router

// Routes maps every client command type of the AsyncAPI (operations receive, x-routing) to its owner module and
// transport (F090-AC-17): KindRequest → NATS request ew.cmd.<module>.<type>; KindRoomInput → NATS core
// ew.in.room.<payload.room_id> without ack; KindLocal → handled by the gateway.
var Routes = map[string]Route{
${types.map((t) => `\t${(JSON.stringify(t) + ':').padEnd(pad)}{Module: ${JSON.stringify(routes.get(t).module)}, Kind: ${routes.get(t).kind}},`).join('\n')}
}
`;
const validateGo = header + `package protocol

// clientTypes are the client command types with a schema in clientSchemaJSON ($defs/msg.<type>).
var clientTypes = []string{
${types.map((t) => `\t${JSON.stringify(t)},`).join('\n')}
}

// clientSchemaJSON bundles components.schemas of the AsyncAPI as $defs plus one $defs/msg.<type> per client command
// (ClientEnvelope + payload: maxLength, enum, required — ADR-0041).
const clientSchemaJSON = ${JSON.stringify(JSON.stringify(bundle))}
`;

const check = process.argv.includes('--check');
let drift = 0;
for (const [file, body] of [[ROUTES, routesGo], [VALIDATE, validateGo]]) {
  const rel = path.relative(repo, file).split(path.sep).join('/');
  if (check) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') : '';
    if (cur !== body) { drift++; console.error(`gen-routes: ${rel} lệch AsyncAPI — chạy node scripts/realtime/gen-routes.mjs`); }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
  }
}
console.log(`gen-routes: ${types.length} type lệnh client, ${drift} file lệch`);
if (drift) process.exit(1);
