// Generates doc_<type>.go from doc_lesson.go in the write and read persistence packages of module learning (F024: the
// composed content types share their columns). Usage (repo root), then gofmt -w:
//   node scripts/dev/gen-learning-docs.mjs src/backend/modules/learning/internal/infrastructure/persistence/write doc_lesson.go
//   node scripts/dev/gen-learning-docs.mjs src/backend/modules/learning/internal/infrastructure/persistence/read doc_lesson.go
import fs from "node:fs";
import path from "node:path";
const [dir, tmpl] = process.argv.slice(2);
const src = fs.readFileSync(path.join(dir, tmpl), "utf8");
const types = [
  { Go: "QuestionSet", lower: "questionSet", pkg: "questionset", file: "question_set", ct: "TypeQuestionSet" },
  { Go: "LearningMaterial", lower: "learningMaterial", pkg: "learningmaterial", file: "learning_material", ct: "TypeLearningMaterial" },
  { Go: "AssessmentBlueprint", lower: "assessmentBlueprint", pkg: "assessmentblueprint", file: "assessment_blueprint", ct: "TypeAssessmentBlueprint" },
  { Go: "Activity", lower: "activity", pkg: "activity", file: "activity", ct: "TypeActivity" },
];
for (const t of types) {
  let s = src;
  s = s.split("ent/lessonversion\"").join("ent/" + t.pkg + "version\"");
  s = s.split("ent/lesson\"").join("ent/" + t.pkg + "\"");
  s = s.split("contentmodel.TypeLesson").join("contentmodel." + t.ct);
  s = s.split("LessonVersion").join(t.Go + "Version");
  s = s.split("LessonID").join(t.Go + "ID");
  s = s.split("Lesson").join(t.Go);
  s = s.split("lessonTable").join(t.lower + "Table");
  s = s.split("lessonDocOf").join(t.lower + "DocOf");
  s = s.split("lessonVersionOf").join(t.lower + "VersionOf");
  s = s.split("lessonModel").join(t.lower + "Model");
  s = s.replace(/^\/\/ [a-zA-Z]+Table is the docTable[\s\S]*?\n(type )/m, "// " + t.lower + "Table is the docTable of " + t.file + " (generated from doc_lesson.go, F024).\n$1");
  s = s.replace(/^\/\/ [a-zA-Z]+Model is[\s\S]*?\n(type )/m, "// " + t.lower + "Model reads " + t.file + " (generated from doc_lesson.go, F024).\n$1");
  s = "// Code generated by scripts/dev/gen-learning-docs.mjs from doc_lesson.go (F024). DO NOT EDIT.\n\n" + s;
  fs.writeFileSync(path.join(dir, "doc_" + t.file + ".go"), s);
}
console.log("ok");
