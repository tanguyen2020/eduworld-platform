#!/usr/bin/env node
// F010 T007 — renders the seed migration of module identity from specs/reference-data (ADR-0060):
// catalog.countries, catalog.provinces (34 active + 63 former units), catalog.province_successions,
// and the common tenant (MULTITENANCY §8.3 [Proposed]): tenant `common`, virtual school and academic
// year. Province ids are UUIDv5 of the province code so the output is stable. The migration is immutable
// once applied (AGENTS R12): --check only verifies it, so this script keeps rendering it byte for byte,
// including the 9 virtual classes common-g1…common-g9 of the original F010 seed; those rows no longer exist
// anywhere: org.classes is dropped by 20261201000001_adr0095_drop_class_enrollment.sql (ADR-0095 mục 8).
// A new seed never creates classes.
//   node scripts/db/gen-identity-seed.mjs [--check]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const OUT = 'src/backend/modules/identity/migrations/20261119000002_f010_seed.sql';
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));

// Fixed identifiers of the common tenant (referenced by Go code: modules/identity/internal/domain/tenant).
export const COMMON = {
  tenant: '0193a000-0000-7000-8000-000000000001',
  school: '0193a000-0000-7000-8000-000000000002',
  year: '0193a000-0000-7000-8000-000000000003',
  classPrefix: '0193a000-0000-7000-8000-0000000000', // + 11…19: history of the applied seed only (ADR-0095)
};

const NS = Buffer.from('6f2a9c1e5b3d4e8fa1c27d9e0b4f6a13', 'hex'); // namespace of catalog ids
export function uuidv5(name) {
  const h = createHash('sha1').update(NS).update(name).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === null || v === undefined ? 'NULL' : `${q(JSON.stringify(v))}::jsonb`);

export function render() {
  const countries = read('specs/reference-data/countries.json').items;
  const provinces = read('specs/reference-data/provinces.vn.json').items;
  const successions = read('specs/reference-data/province-successions.vn.json').items;
  const id = Object.fromEntries(provinces.map((p) => [p.code, uuidv5(`province:${p.code}`)]));
  const out = [];
  out.push(`-- Code generated by scripts/db/gen-identity-seed.mjs from specs/reference-data. DO NOT EDIT.
-- F010 T007: catalog (ADR-0060; official_code NULL until verified, [TBD]) and the common tenant
-- (MULTITENANCY §8.3 [Proposed]). Applied as identity_migrator; org.* rows need app.tenant_id (FORCE RLS).
`);
  out.push('INSERT INTO catalog.countries (country_code, created_at, updated_at, name_i18n, default_locale, status) VALUES');
  out.push(countries.map((c) => `  (${q(c.country_code)}, now(), now(), ${j(c.name)}, ${q(c.default_locale)}, ${q(c.status)})`).join(',\n') + ';\n');
  out.push('INSERT INTO catalog.provinces (province_id, created_at, updated_at, country_code, code, official_code, name_i18n, short_name_i18n, province_type, effective_from, effective_to, status) VALUES');
  out.push(provinces.map((p) => `  (${q(id[p.code])}, now(), now(), ${q(p.country_code)}, ${q(p.code)}, ${q(p.official_code)}, ${j(p.name)}, ${j(p.short_name)}, ${q(p.type)}, ${q(p.effective_from)}, ${q(p.effective_to)}, ${q(p.status)})`).join(',\n') + ';\n');
  out.push('INSERT INTO catalog.province_successions (old_province_id, created_at, updated_at, new_province_id, effective_date, kind) VALUES');
  out.push(successions.map((s) => {
    if (!id[s.old_code] || !id[s.new_code]) throw new Error(`succession ${s.old_code} → ${s.new_code}: unknown province`);
    return `  (${q(id[s.old_code])}, now(), now(), ${q(id[s.new_code])}, ${q(s.effective_date)}, ${q(s.kind)})`;
  }).join(',\n') + ';\n');
  out.push(`-- Common tenant: the only tenant_type = 'common' (tenants_single_common_uq).
INSERT INTO platform.tenants (tenant_id, created_at, updated_at, code, name, tenant_type, status, keycloak_org_alias, settings, is_qa)
  VALUES ('${COMMON.tenant}', now(), now(), 'common', 'EduWorld chung', 'common', 'active', 'common', '{}'::jsonb, false);

SELECT set_config('app.tenant_id', '${COMMON.tenant}', true);
INSERT INTO org.schools (school_id, tenant_id, created_at, updated_at, code, name, name_i18n, country_code, province_id,
    school_level, grade_min, grade_max, status, is_virtual, settings)
  VALUES ('${COMMON.school}', '${COMMON.tenant}', now(), now(), 'common', 'EduWorld chung',
    '{"vi":"EduWorld chung","en":"EduWorld Common"}'::jsonb, 'VN', NULL, 'multi_level', 1, 9, 'active', true, '{}'::jsonb);
INSERT INTO org.academic_years (academic_year_id, tenant_id, created_at, updated_at, school_id, name, start_date, end_date, is_current)
  VALUES ('${COMMON.year}', '${COMMON.tenant}', now(), now(), '${COMMON.school}', 'common', '2025-08-01', '2099-07-31', true);
INSERT INTO org.classes (class_id, tenant_id, created_at, updated_at, school_id, academic_year_id, grade_level, name, is_virtual, status) VALUES`);
  out.push([1, 2, 3, 4, 5, 6, 7, 8, 9].map((g) =>
    `  ('${COMMON.classPrefix}${10 + g}', '${COMMON.tenant}', now(), now(), '${COMMON.school}', '${COMMON.year}', ${g}, 'common-g${g}', true, 'active')`).join(',\n') + ';');
  out.push(`SELECT set_config('app.tenant_id', '', true);\n`);
  return out.join('\n');
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  const sql = render();
  const file = new URL(OUT, root);
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    if (cur !== sql) { console.error(`stale: ${OUT}`); process.exit(1); }
    console.log(`${OUT} up to date`);
  } else {
    writeFileSync(file, sql);
    console.log(`wrote ${OUT}`);
  }
}
