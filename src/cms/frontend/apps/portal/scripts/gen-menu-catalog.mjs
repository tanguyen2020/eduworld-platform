// pnpm gen:catalog / gen:check (F051 T054, F051-AC-34, ADR-0090): from the portal menu/action catalog
//   specs/portal/menu-catalog.yaml (the single source, checked by scripts/specs/check-portal-catalog.mjs)
// generates src/generated/menu-catalog.ts: workspace → menu → action tree (key, path, label key, required
// permissions any-of, order) and the union types WorkspaceKey, MenuKey, ActionKey. No menu is declared by hand
// in TSX. `--check` regenerates in memory and fails (exit 1) when the committed file differs (CI gen:check).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PORTAL_DIR = path.resolve(HERE, '..');
export const REPO_ROOT = path.resolve(PORTAL_DIR, '..', '..', '..', '..', '..');
export const CATALOG = path.join(REPO_ROOT, 'specs/portal/menu-catalog.yaml');
export const OUT = path.join(PORTAL_DIR, 'src/generated/menu-catalog.ts');

const MARK = 'GENERATED by pnpm gen:catalog (make portal-catalog) from specs/portal/menu-catalog.yaml — DO NOT EDIT (ADR-0090)';

const q = (s) => JSON.stringify(s);
const byOrder = (a, b) => a.order - b.order || a.key.localeCompare(b.key);
const union = (keys) => (keys.length ? keys.map((k) => `\n  | ${q(k)}`).join('') : ' never');

/** Builds the TypeScript source of the generated catalog from the parsed YAML. */
export function buildCatalogSource(catalog) {
  const workspaces = [...(catalog.workspaces ?? [])].sort(byOrder);
  const menuKeys = [];
  const actionKeys = [];
  const wsSource = workspaces.map((ws) => {
    const menus = [...ws.menus].sort(byOrder).map((m) => {
      menuKeys.push(m.key);
      const actions = m.actions.map((a) => {
        actionKeys.push(a.key);
        return `        { key: ${q(a.key)}, labelKey: ${q(a.label_key)}, requiredPermissions: [${a.required_permissions.map(q).join(', ')}] },`;
      });
      return [
        `      {`,
        `        key: ${q(m.key)},`,
        `        path: ${q(m.path)},`,
        `        labelKey: ${q(m.label_key)},`,
        `        order: ${m.order},`,
        `        requiredPermissions: [${m.required_permissions.map(q).join(', ')}],`,
        `        actions: [`,
        ...actions.map((l) => `  ${l}`),
        `        ],`,
        `      },`,
      ].join('\n');
    });
    return [
      `  {`,
      `    key: ${q(ws.key)},`,
      `    path: ${q(ws.path)},`,
      `    labelKey: ${q(ws.label_key)},`,
      `    order: ${ws.order},`,
      `    menus: [`,
      ...menus,
      `    ],`,
      `  },`,
    ].join('\n');
  });
  return `// ${MARK}
// catalog_version ${catalog.catalog_version}. Shape: specs/051-portal-shell/data-model.md (operation_ids, can_disable are
// not needed by the client). requiredPermissions are any-of (ADR-0090 mục 1).

export const CATALOG_VERSION = ${q(catalog.catalog_version)};

export type WorkspaceKey =${union(workspaces.map((w) => w.key))};

export type MenuKey =${union(menuKeys)};

export type ActionKey =${union(actionKeys)};

export interface ActionDef {
  readonly key: ActionKey;
  readonly labelKey: string;
  readonly requiredPermissions: readonly string[];
}

export interface MenuDef {
  readonly key: MenuKey;
  readonly path: string;
  readonly labelKey: string;
  readonly order: number;
  readonly requiredPermissions: readonly string[];
  readonly actions: readonly ActionDef[];
}

export interface WorkspaceDef {
  readonly key: WorkspaceKey;
  readonly path: string;
  readonly labelKey: string;
  readonly order: number;
  readonly menus: readonly MenuDef[];
}

export const WORKSPACE_CATALOG: readonly WorkspaceDef[] = [
${wsSource.join('\n')}
];
`;
}

export function generate() {
  return buildCatalogSource(yaml.load(fs.readFileSync(CATALOG, 'utf8')));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const content = generate();
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== content) {
      console.error('gen:check: src/generated/menu-catalog.ts differs from specs/portal/menu-catalog.yaml (run pnpm gen:catalog)');
      process.exit(1);
    }
    console.log('gen:check: src/generated/menu-catalog.ts matches specs/portal/menu-catalog.yaml');
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, content);
    console.log(`gen:catalog: wrote ${path.relative(PORTAL_DIR, OUT)}`);
  }
}
