// pnpm gen:api / gen:check (F050 T005, F050-AC-10): from the merged spec specs/openapi/eduworld-api.v1.yaml
//   src/shared/api/schema.gen.d.ts      openapi-typescript types (`paths`, `components`, `operations`)
//   src/shared/api/operation-meta.gen.ts metadata per operation: gateway, tenantHeader, idempotency, ifMatch
// `--check` regenerates in memory and fails (exit 1) when a committed file differs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PORTAL_DIR = path.resolve(HERE, '..');
export const REPO_ROOT = path.resolve(PORTAL_DIR, '..', '..', '..', '..', '..');
export const SPEC = path.join(REPO_ROOT, 'specs/openapi/eduworld-api.v1.yaml');
export const OUT_TYPES = path.join(PORTAL_DIR, 'src/shared/api/schema.gen.d.ts');
export const OUT_META = path.join(PORTAL_DIR, 'src/shared/api/operation-meta.gen.ts');

const MARK = 'GENERATED by pnpm gen:api from specs/openapi/eduworld-api.v1.yaml — DO NOT EDIT';

/** API_DESIGN §10 / Clarification 2026-11-16: these prefixes go through the internal gateway (VPN). */
export const INTERNAL_PREFIXES = ['/admin/', '/sis/', '/game-admin/', '/game-media'];

const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options'];

export function gatewayFor(p) {
  return INTERNAL_PREFIXES.some((pre) => p.startsWith(pre) || `${p}/`.startsWith(pre)) ? 'internal' : 'public';
}

const refName = (param) => (typeof param?.$ref === 'string' ? param.$ref.split('/').pop() : null);

/** Resolves a parameter ($ref to components.parameters) to {name, in, required, ref}. */
function resolveParam(spec, param) {
  const ref = refName(param);
  const p = ref ? spec.components?.parameters?.[ref] : param;
  return p ? { name: p.name, in: p.in, required: !!p.required, ref } : null;
}

/** Builds the sorted operation metadata list from a parsed spec. */
export function buildOperationMeta(spec) {
  const out = [];
  for (const [p, item] of Object.entries(spec.paths ?? {})) {
    const shared = item.parameters ?? [];
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const params = [...shared, ...(op.parameters ?? [])].map((x) => resolveParam(spec, x)).filter(Boolean);
      const header = (name) => params.find((x) => x.in === 'header' && x.name.toLowerCase() === name.toLowerCase());
      const tenant = header('X-Tenant-Id');
      const idem = header('Idempotency-Key');
      const ifMatch = header('If-Match');
      out.push({
        operationId: op.operationId,
        method: method.toUpperCase(),
        path: p,
        service: op['x-service'] ?? item['x-service'] ?? null,
        gateway: gatewayFor(p),
        tenantHeader: tenant ? (tenant.required ? 'required' : 'optional') : 'none',
        idempotency: !!idem?.required,
        ifMatch: !!ifMatch,
      });
    }
  }
  return out.sort((a, b) => (a.path === b.path ? a.method.localeCompare(b.method) : a.path < b.path ? -1 : 1));
}

export function formatOperationMeta(list) {
  const rows = list.map((o) => `  { ${Object.entries(o).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ')} },`).join('\n');
  return `// ${MARK}
import type { OperationMeta } from './types';

export const OPERATION_COUNT = ${list.length};

export const operations: readonly OperationMeta[] = [
${rows}
];
`;
}

/** Headers the apiClient sets itself from metadata (F050-AC-11, AC-12): optional in the generated types. */
export const CLIENT_MANAGED_HEADERS = ['x-tenant-id', 'idempotency-key', 'if-match', 'accept-language'];

/** Copy of the spec where client-managed header parameters are optional (types only; metadata uses the original). */
export function forTypes(spec) {
  const copy = structuredClone(spec);
  const relax = (p) => {
    if (p && p.in === 'header' && CLIENT_MANAGED_HEADERS.includes(String(p.name).toLowerCase())) p.required = false;
  };
  for (const p of Object.values(copy.components?.parameters ?? {})) relax(p);
  for (const item of Object.values(copy.paths ?? {})) {
    for (const p of item.parameters ?? []) relax(p);
    for (const m of METHODS) for (const p of item[m]?.parameters ?? []) relax(p);
  }
  return copy;
}

export async function generateTypes(spec) {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(forTypes(spec), { alphabetize: true });
  return `// ${MARK}\n${astToString(ast)}`;
}

export async function generateAll(specPath = SPEC) {
  const spec = yaml.load(fs.readFileSync(specPath, 'utf8'));
  return new Map([
    [OUT_META, formatOperationMeta(buildOperationMeta(spec))],
    [OUT_TYPES, await generateTypes(spec)],
  ]);
}

/** Files (absolute path → expected content) whose committed content differs; repo-relative paths. */
export function findDrift(files) {
  const drift = [];
  for (const [file, content] of files) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current !== content) drift.push(path.relative(REPO_ROOT, file).split(path.sep).join('/'));
  }
  return drift;
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await generateAll();
  const drift = check ? findDrift(files) : [];
  if (!check) {
    for (const [file, content] of files) {
      fs.writeFileSync(file, content);
      console.log(`wrote ${path.relative(REPO_ROOT, file).split(path.sep).join('/')}`);
    }
  }
  if (drift.length) {
    console.error(`gen:check: generated API files differ from specs/openapi (run pnpm gen:api):\n  ${drift.join('\n  ')}`);
    process.exit(1);
  }
  if (check) console.log(`gen:check: ${files.size} file(s) match specs/openapi/eduworld-api.v1.yaml`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
