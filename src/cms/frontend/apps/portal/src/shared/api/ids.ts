// Client-side identifiers: UUIDv7 for Idempotency-Key (ADR-0089 §4, F050-AC-12) and W3C traceparent.

type RandomFn = (bytes: Uint8Array) => Uint8Array;
const defaultRandom: RandomFn = (b) => crypto.getRandomValues(b);

const hex = (bytes: Uint8Array) => Array.from(bytes, (x) => x.toString(16).padStart(2, '0')).join('');

/** RFC 9562 UUID version 7: 48-bit Unix ms timestamp, version 7, variant 10, random rest. */
export function uuidv7(now: number = Date.now(), random: RandomFn = defaultRandom): string {
  const b = new Uint8Array(16);
  let ts = Math.floor(now);
  for (let i = 5; i >= 0; i--) {
    b[i] = ts % 256;
    ts = Math.floor(ts / 256);
  }
  const r = random(new Uint8Array(10));
  b[6] = 0x70 | (r[0]! & 0x0f);
  b[7] = r[1]!;
  b[8] = 0x80 | (r[2]! & 0x3f);
  for (let i = 0; i < 7; i++) b[9 + i] = r[3 + i]!;
  const h = hex(b);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

export const UUIDV7 = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

/** Timestamp (ms) encoded in a UUIDv7. */
export function uuidv7Time(id: string): number {
  return parseInt(id.replace(/-/g, '').slice(0, 12), 16);
}

/** W3C Trace Context `traceparent` generated by the client (plan: Quan sát). */
export function traceparent(random: RandomFn = defaultRandom): string {
  return `00-${hex(random(new Uint8Array(16)))}-${hex(random(new Uint8Array(8)))}-01`;
}
