#!/usr/bin/env node
// F071 T027 — greybox zone scenes of the 12 world areas, generated from the world seed of module game
// (src/backend/modules/game/seed/world/areas.v1.json): the anchors (spawn points, wind gates, NPCs, discoveries,
// collectibles, boards) carry the ids of the area layout, so the zone lint (tools/zone_lint.gd) and the server agree.
// PLACEHOLDER art (AGENTS R17; ADR-0102: first-party MIT art, F067 did main_hub only): boxes without materials; the
// environment comes from the generated design tokens (resources/art/generated/env_*.tres, R32).
// Hand-made scenes keep everything above the marker and get only a generated block (anchors of F071) between the
// markers: main_hub (F062/F067/F068, a few anchors placed by hand) and every zone of an art pass (F093) — a scene
// that already carries the BEGIN marker is never regenerated as a greybox.
//
//   node src/game/tools/gen_greybox_zones.mjs           write the scenes
//   node src/game/tools/gen_greybox_zones.mjs --check   exit 1 when a scene differs from the seed
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(game, '..', '..');
const areas = JSON.parse(fs.readFileSync(path.join(repo, 'src/backend/modules/game/seed/world/areas.v1.json'), 'utf8'));
const check = process.argv.includes('--check');
const ENV = { math: 'env_math', vietnamese: 'env_vietnamese', english: 'env_english', science: 'env_science', history: 'env_history' };
const BEGIN = '; BEGIN F071 generated anchors (tools/gen_greybox_zones.mjs)';
const END = '; END F071 generated anchors';

const v = (p) => `${p[0]}, ${p[1]}, ${p[2]}`;
const xform = (p) => `Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, ${v(p)})`;
const nodeName = (id) => id.split(/[._-]/).map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join('');

function anchors(a, { skipSpawns = [], skipInteractables = [] } = {}) {
  const out = [];
  for (const s of a.layout.spawn_points) {
    if (skipSpawns.includes(s.spawn_point_id)) continue;
    out.push(`[node name="${nodeName(s.spawn_point_id)}" type="Marker3D" parent="SpawnPoints"]\ntransform = ${xform(s.position)}\n` +
      `script = ExtResource("3_spawn")\nspawn_point_id = "${s.spawn_point_id}"\nradius = 1.0\n`);
  }
  (a.layout.portals ?? []).forEach((p, i) => {
    const x = -2.5 * ((a.layout.portals.length - 1) / 2) * 2 + i * 5;
    out.push(`[node name="${nodeName(p.portal_id)}" parent="Portals" instance=ExtResource("6_portal")]\n` +
      `transform = ${xform([x, 0, -20])}\ninteractable_id = "${p.portal_id}"\ntarget_area_id = "${p.target_area_id}"\n`);
  });
  for (const it of a.layout.interactables ?? []) {
    if (skipInteractables.includes(it.interactable_id)) continue;
    const pos = it.position ?? [0, 0, 0];
    if (it.kind === 'npc') {
      out.push(`[node name="${nodeName(it.interactable_id)}" parent="Interactables" instance=ExtResource("7_npc")]\n` +
        `transform = ${xform(pos)}\ninteractable_id = "${it.interactable_id}"\nnpc_id = "${it.npc_id}"\n`);
    } else {
      out.push(`[node name="${nodeName(it.interactable_id)}" parent="Interactables" instance=ExtResource("8_anchor")]\n` +
        `transform = ${xform(pos)}\ninteractable_id = "${it.interactable_id}"\nkind = "${it.kind}"\n` +
        `prompt_key = "ui.world.action.${it.kind === 'discovery' || it.kind === 'collectible' ? 'inspect' : 'interact'}"\n`);
    }
  }
  return out.join('\n');
}

const RES = `[ext_resource type="PackedScene" path="res://scenes/world/AreaPortal.tscn" id="6_portal"]
[ext_resource type="PackedScene" path="res://scenes/npc/NPC.tscn" id="7_npc"]
[ext_resource type="PackedScene" path="res://scenes/world/WorldAnchor.tscn" id="8_anchor"]`;

function zone(a) {
  const env = ENV[a.subject_code] ?? 'env_hub';
  const half = Math.max(10, Math.min(30, a.bounds.max[0] - 5));
  return `[gd_scene load_steps=12 format=3]

; GENERATED by tools/gen_greybox_zones.mjs from the world seed — do not edit by hand (F071 T027).
; PLACEHOLDER greybox (AGENTS R17, OQ-16): stylized low-poly art replaces the meshes, the anchors keep their ids.

[ext_resource type="Script" path="res://scripts/world/zone_root.gd" id="1_zone"]
[ext_resource type="Environment" path="res://resources/art/generated/${env}.tres" id="2_env"]
[ext_resource type="Script" path="res://scripts/world/spawn_point.gd" id="3_spawn"]
[ext_resource type="PackedScene" path="res://scenes/character/Player.tscn" id="5_player"]
${RES}

[sub_resource type="BoxShape3D" id="BoxShape3D_ground"]
size = Vector3(${half * 2}, 1, ${half * 2})

[sub_resource type="BoxMesh" id="BoxMesh_ground"]
size = Vector3(${half * 2}, 1, ${half * 2})

[node name="Zone" type="Node3D"]
script = ExtResource("1_zone")
area_id = "${a.area_id}"
default_spawn = "${a.area_id}.default"
player_scene = ExtResource("5_player")

[node name="Environment" type="Node3D" parent="."]

[node name="WorldEnvironment" type="WorldEnvironment" parent="Environment"]
environment = ExtResource("2_env")

[node name="Sun" type="DirectionalLight3D" parent="Environment"]
transform = Transform3D(0.8660254, -0.25, 0.4330127, 0, 0.8660254, 0.5, -0.5, -0.4330127, 0.75, 0, 12, 0)
shadow_enabled = true
directional_shadow_mode = 0
directional_shadow_max_distance = 25.0

[node name="Terrain" type="StaticBody3D" parent="."]

[node name="Collision" type="CollisionShape3D" parent="Terrain"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.5, 0)
shape = SubResource("BoxShape3D_ground")

[node name="Ground" type="MeshInstance3D" parent="Terrain"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.5, 0)
mesh = SubResource("BoxMesh_ground")

[node name="Static" type="StaticBody3D" parent="."]

[node name="Navigation" type="NavigationRegion3D" parent="."]

[node name="Occluders" type="Node3D" parent="."]

[node name="SpawnPoints" type="Node3D" parent="."]

[node name="Interactables" type="Node3D" parent="."]

[node name="Portals" type="Node3D" parent="."]

[node name="Players" type="Node3D" parent="."]

[node name="Ambient" type="Node3D" parent="."]

${anchors(a)}`;
}

// Anchors placed by hand in a hand-made scene (not repeated in the generated block).
const HAND_ANCHORS = {
  main_hub: { skipSpawns: ['main_hub.default', 'main_hub.from_arena'], skipInteractables: ['board.school_assignments', 'board.exam_sessions'] },
};

function anchorBlock(a) {
  return `${BEGIN}\n\n${anchors(a, HAND_ANCHORS[a.area_id] ?? {})}\n${END}\n`;
}

let drift = 0;
const write = (file, text) => {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (old === text) return;
  if (check) { drift++; console.log(`stale: ${path.relative(repo, file)}`); return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote ${path.relative(repo, file)}`);
};
for (const a of areas) {
  const file = path.join(game, 'scenes/world/zones', a.area_id.replace('.', '_'), 'Zone.tscn');
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (a.area_id !== 'main_hub' && !old.includes(BEGIN)) {
    write(file, zone(a));
    continue;
  }
  let hand = old;
  const i = hand.indexOf(BEGIN);
  if (i >= 0) hand = hand.slice(0, i);
  hand = hand.replace(/\n*$/, '\n\n');
  if (!hand.includes('id="6_portal"')) {
    hand = hand.replace('[ext_resource type="PackedScene" path="res://scenes/character/Player.tscn" id="5_player"]',
      `[ext_resource type="PackedScene" path="res://scenes/character/Player.tscn" id="5_player"]\n${RES}`);
  }
  write(file, hand + anchorBlock(a));
}
if (drift) process.exit(1);
console.log(`gen_greybox_zones: ${areas.length} zones ${check ? 'checked' : 'up to date'}`);
