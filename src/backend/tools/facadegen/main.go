// Command facadegen generates the typed facade of every module (ADR-0074, R29): it bundles
// specs/openapi/modules/<m>.internal.v1.yaml (internalizing external $refs) and runs the pinned
// oapi-codegen (models + strict-server interface, no HTTP server) into modules/<m>/api/facade_gen.go.
//
//	go run ./tools/facadegen [--check] [--oapi=oapi-codegen] [module...]
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

var modules = []string{"identity", "learning", "game", "competition", "chat"}

func main() {
	check := flag.Bool("check", false, "fail when a generated facade differs")
	oapi := flag.String("oapi", "oapi-codegen", "oapi-codegen binary (pinned in tools/versions.mk)")
	specs := flag.String("specs", filepath.Join("..", "..", "specs", "openapi", "modules"), "internal specs directory")
	flag.Parse()
	targets := flag.Args()
	if len(targets) == 0 {
		targets = modules
	}
	tmp, err := os.MkdirTemp("", "facadegen")
	if err != nil {
		fail(err)
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	var stale []string
	for _, m := range targets {
		src, err := generate(*oapi, filepath.Join(*specs, m+".internal.v1.yaml"), tmp, m)
		if err != nil {
			fail(fmt.Errorf("%s: %w", m, err))
		}
		out := filepath.Join("modules", m, "api", "facade_gen.go")
		if *check {
			cur, err := os.ReadFile(out)
			if err != nil || !bytes.Equal(bytes.ReplaceAll(cur, []byte("\r\n"), []byte("\n")), src) {
				stale = append(stale, out)
			}
			continue
		}
		if err := os.WriteFile(out, src, 0o644); err != nil {
			fail(err)
		}
	}
	if len(stale) > 0 {
		fail(fmt.Errorf("stale (run `make gen`): %s", strings.Join(stale, ", ")))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "facadegen:", err)
	os.Exit(1)
}

func generate(oapi, spec, tmp, module string) ([]byte, error) {
	l := openapi3.NewLoader()
	l.IsExternalRefsAllowed = true
	doc, err := l.LoadFromFile(spec)
	if err != nil {
		return nil, err
	}
	doc.InternalizeRefs(context.Background(), nil)
	raw, err := json.Marshal(doc)
	if err != nil {
		return nil, err
	}
	if raw, err = normalize(raw); err != nil {
		return nil, err
	}
	bundled := filepath.Join(tmp, module+".json")
	if err := os.WriteFile(bundled, raw, 0o644); err != nil {
		return nil, err
	}
	cfg := filepath.Join(tmp, module+".cfg.yaml")
	conf := "package: api\ngenerate:\n  models: true\n  strict-server: true\n  std-http-server: true\noutput-options:\n  skip-prune: true\n"
	if err := os.WriteFile(cfg, []byte(conf), 0o644); err != nil {
		return nil, err
	}
	out := filepath.Join(tmp, module+".go")
	cmd := exec.Command(oapi, "-config", cfg, "-o", out, bundled)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("oapi-codegen: %w: %s", err, stderr.String())
	}
	b, err := os.ReadFile(out)
	if err != nil {
		return nil, err
	}
	header := "// Facade of module " + module + " generated by tools/facadegen from specs/openapi/modules/" + module +
		".internal.v1.yaml (ADR-0074).\n// Callers use it in process through pkg/modcall; the HTTP server code is never mounted (no internal HTTP).\n"
	return append([]byte(header), b...), nil
}

// normalize rewrites OpenAPI 3.1 constructs the pinned oapi-codegen cannot read, for type generation
// only (request validation uses the real spec through kin-openapi): a tuple (prefixItems + items:false)
// becomes an array of its first element type; any other boolean schema under items becomes {}.
func normalize(raw []byte) ([]byte, error) {
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		return nil, err
	}
	var walk func(any)
	walk = func(n any) {
		switch x := n.(type) {
		case map[string]any:
			if b, ok := x["items"].(bool); ok {
				if prefix, ok := x["prefixItems"].([]any); ok && len(prefix) > 0 && !b {
					x["items"] = prefix[0]
				} else {
					x["items"] = map[string]any{}
				}
				delete(x, "prefixItems")
			}
			for _, c := range x {
				walk(c)
			}
		case []any:
			for _, c := range x {
				walk(c)
			}
		}
	}
	walk(v)
	return json.Marshal(v)
}
