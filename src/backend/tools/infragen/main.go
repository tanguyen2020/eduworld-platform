// Command infragen writes the hand-written infra migration (outbox, processed events, dead letters,
// idempotency records — DATABASE_DESIGN §3.9–3.10, ADR-0089 §4–6) for every module database from one
// template, so the five copies cannot drift. ent/Atlas cannot express PARTITION BY, hence SQL.
//
//	go run ./tools/infragen           # write modules/<m>/migrations/<version>_infra.sql
//	go run ./tools/infragen --check   # fail when a file differs from the template
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// Version is the Atlas version of the infra migration (after the F001 baseline).
const Version = "20261118000001"

// Modules with a database (realtime has none, ADR-0074).
var Modules = []string{"identity", "learning", "game", "competition", "chat"}

func main() {
	check := flag.Bool("check", false, "fail when a generated migration is stale")
	root := flag.String("root", ".", "Go module root (src/backend)")
	flag.Parse()
	var stale []string
	for _, m := range Modules {
		for _, f := range Files {
			want, err := renderWith(f.tmpl, m)
			if err != nil {
				fmt.Fprintln(os.Stderr, "infragen:", err)
				os.Exit(1)
			}
			path := filepath.Join(*root, "modules", m, "migrations", f.Version+"_"+f.Name+".sql")
			if *check {
				cur, err := os.ReadFile(path)
				if err != nil || !bytes.Equal(bytes.ReplaceAll(cur, []byte("\r\n"), []byte("\n")), want) {
					stale = append(stale, path)
				}
				continue
			}
			if err := os.WriteFile(path, want, 0o644); err != nil {
				fmt.Fprintln(os.Stderr, "infragen:", err)
				os.Exit(1)
			}
		}
	}
	if len(stale) > 0 {
		fmt.Fprintln(os.Stderr, "infragen: stale (run `make gen`, then re-hash atlas.sum):", strings.Join(stale, ", "))
		os.Exit(1)
	}
}

// File is one generated migration (immutable once applied: later fixes are new files, AGENTS R12).
type File struct {
	Version string
	Name    string
	tmpl    *template.Template
}

// Files are rendered for every module, in version order.
var Files = []File{
	{Version: Version, Name: "infra", tmpl: tmpl},
	{Version: PlatformGrantsVersion, Name: "infra_platform_grants", tmpl: platformGrants},
	{Version: ReconcileGrantsVersion, Name: "infra_reconcile_grants", tmpl: reconcileGrants},
}

// PlatformGrantsVersion is the Atlas version of the platform-role grants on the infra tables (F010).
const PlatformGrantsVersion = "20261119000010"

// ReconcileGrantsVersion is the Atlas version of the reconciliation read grant (F134): after the last migration of
// every module, so each module applies it last.
const ReconcileGrantsVersion = "20270201000134"

// Render returns the infra migration of module m.
func Render(m string) ([]byte, error) { return renderWith(tmpl, m) }

func renderWith(t *template.Template, m string) ([]byte, error) {
	var b bytes.Buffer
	if err := t.Execute(&b, map[string]string{"M": m}); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

var platformGrants = template.Must(template.New("grants").Delims("[[", "]]").Parse(`-- Code generated by tools/infragen (F010). DO NOT EDIT — change the template and run ` + "`make gen`" + `.
-- Transactions under PlatformScope / SystemPlatformScope run as [[.M]]_platform (entx.UnitOfWork, ADR-0089 §3):
-- System Admin writes and platform consumers write the outbox, idempotency records and processed events in
-- the same transaction, like [[.M]]_app (ADR-0089 §4). Still no UPDATE/DELETE of these rows.
GRANT INSERT ON infra.outbox_events TO [[.M]]_platform;
GRANT INSERT, SELECT ON infra.processed_events, infra.idempotency_records TO [[.M]]_platform;
GRANT INSERT ON infra.dead_letters TO [[.M]]_platform;
`))

var reconcileGrants = template.Must(template.New("reconcile").Delims("[[", "]]").Parse(`-- Code generated by tools/infragen (F134). DO NOT EDIT — change the template and run ` + "`make gen`" + `.
-- worker reconcile --module=<module> (F134 US1, BACKUP_RECOVERY §3.5) reads the outbox through the facade operation
-- listOutboxEventIds on the [[.M]]_platform pool: ids and metadata only (column grant, never the envelope — AGENTS R14).
-- processed_events and dead_letters are already readable by [[.M]]_platform. Still no UPDATE/DELETE.
GRANT SELECT (event_id, event_type, tenant_id, created_at, published_at) ON infra.outbox_events TO [[.M]]_platform;
`))

var tmpl = template.Must(template.New("infra").Delims("[[", "]]").Parse(`-- Code generated by tools/infragen (F003 T007/T008/T066). DO NOT EDIT — change the template and run ` + "`make gen`" + `.
-- Infra tables of eduworld_[[.M]] (DATABASE_DESIGN §3.9–3.10, ADR-0089 §4–6): no RLS, no DELETE/TRUNCATE for any
-- application role, partitioned by day; retention by dropping partitions through SECURITY DEFINER functions
-- that the job infra-partition-maintenance ([[.M]]_partition_admin) may only EXECUTE.

CREATE TABLE infra.outbox_events (
  event_id      uuid NOT NULL,
  event_type    varchar(64) NOT NULL,
  subject       varchar(128) NOT NULL,
  tenant_id     uuid,
  partition_key varchar(128) NOT NULL,
  envelope      jsonb NOT NULL CHECK (octet_length(envelope::text) <= 65536),
  created_at    timestamptz NOT NULL DEFAULT now(),
  published_at  timestamptz,
  attempts      int NOT NULL DEFAULT 0,
  PRIMARY KEY (event_id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX outbox_unpublished_idx ON infra.outbox_events (event_id) WHERE published_at IS NULL;

CREATE TABLE infra.processed_events (
  consumer          varchar(128) NOT NULL,
  event_id          uuid NOT NULL,
  event_occurred_at timestamptz NOT NULL,
  processed_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (consumer, event_id, event_occurred_at)
) PARTITION BY RANGE (event_occurred_at);

CREATE TABLE infra.dead_letters (
  dead_letter_id uuid NOT NULL,
  stream         varchar(64) NOT NULL,
  consumer       varchar(128) NOT NULL,
  event_id       uuid NOT NULL,
  event_type     varchar(64) NOT NULL,
  payload        jsonb NOT NULL CHECK (octet_length(payload::text) <= 65536),
  error          varchar(1000) NOT NULL,
  delivery_count int NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  resolved_at    timestamptz,
  resolved_by    uuid,
  PRIMARY KEY (dead_letter_id, created_at),
  UNIQUE (consumer, event_id, created_at)
) PARTITION BY RANGE (created_at);

CREATE TABLE infra.idempotency_records (
  user_id         uuid NOT NULL,
  method          varchar(16) NOT NULL,
  route_template  varchar(255) NOT NULL,
  idem_key        uuid NOT NULL,
  key_issued_on   date NOT NULL,
  request_hash    bytea NOT NULL CHECK (octet_length(request_hash) = 32),
  response_status smallint NOT NULL,
  response_body   jsonb CHECK (response_body IS NULL OR octet_length(response_body::text) <= 65536),
  created_at      timestamptz NOT NULL DEFAULT now(),
  expires_at      timestamptz NOT NULL,
  PRIMARY KEY (user_id, route_template, idem_key, key_issued_on)
) PARTITION BY RANGE (key_issued_on);
CREATE INDEX idempotency_expires_idx ON infra.idempotency_records (expires_at);

-- Default partitions keep writes working if a daily partition is missing (alert: rows in *_default).
CREATE TABLE infra.outbox_events_default PARTITION OF infra.outbox_events DEFAULT;
CREATE TABLE infra.processed_events_default PARTITION OF infra.processed_events DEFAULT;
CREATE TABLE infra.dead_letters_default PARTITION OF infra.dead_letters DEFAULT;
CREATE TABLE infra.idempotency_records_default PARTITION OF infra.idempotency_records DEFAULT;

-- Privileges (ADR-0089 §4). The baseline default privileges granted SELECT, INSERT, UPDATE on every new
-- table to [[.M]]_app/[[.M]]_platform: take them back, then grant exactly what each role needs.
REVOKE ALL ON infra.outbox_events, infra.processed_events, infra.dead_letters, infra.idempotency_records,
  infra.outbox_events_default, infra.processed_events_default, infra.dead_letters_default, infra.idempotency_records_default
  FROM [[.M]]_app, [[.M]]_platform;
GRANT INSERT ON infra.outbox_events TO [[.M]]_app;
GRANT INSERT, SELECT ON infra.processed_events, infra.idempotency_records TO [[.M]]_app;
GRANT INSERT ON infra.dead_letters TO [[.M]]_app;
GRANT USAGE ON SCHEMA infra TO [[.M]]_relay, [[.M]]_partition_admin;
GRANT SELECT, UPDATE (published_at, attempts) ON infra.outbox_events TO [[.M]]_relay;
GRANT SELECT, UPDATE (resolved_at, resolved_by) ON infra.dead_letters TO [[.M]]_platform;

-- Daily partitions [p_from, p_from + p_days). Runs as the table owner; new partitions get no grant (access
-- goes through the parent). A day whose rows already sit in the default partition is skipped with a warning.
CREATE FUNCTION infra.ensure_partitions(p_from date, p_days int) RETURNS int
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, infra AS $$
DECLARE
  t text; d date; part text; lo text; hi text; g record; created int := 0;
BEGIN
  IF p_days < 1 OR p_days > 62 THEN
    RAISE EXCEPTION 'p_days must be within 1..62';
  END IF;
  FOREACH t IN ARRAY ARRAY['outbox_events', 'processed_events', 'dead_letters', 'idempotency_records'] LOOP
    FOR i IN 0 .. p_days - 1 LOOP
      d := p_from + i;
      part := t || '_p' || to_char(d, 'YYYYMMDD');
      CONTINUE WHEN to_regclass('infra.' || part) IS NOT NULL;
      IF t = 'idempotency_records' THEN
        lo := d::text; hi := (d + 1)::text;
      ELSE
        lo := d::text || ' 00:00:00+00'; hi := (d + 1)::text || ' 00:00:00+00';
      END IF;
      BEGIN
        EXECUTE format('CREATE TABLE infra.%I PARTITION OF infra.%I FOR VALUES FROM (%L) TO (%L)', part, t, lo, hi);
        FOR g IN SELECT DISTINCT grantee FROM information_schema.role_table_grants
                 WHERE table_schema = 'infra' AND table_name = part AND grantee <> current_user LOOP
          EXECUTE format('REVOKE ALL ON infra.%I FROM %I', part, g.grantee);
        END LOOP;
        created := created + 1;
      EXCEPTION WHEN check_violation THEN
        RAISE WARNING 'infra partition % skipped: rows for that day are in the default partition', part;
      END;
    END LOOP;
  END LOOP;
  RETURN created;
END $$;

-- Number of consecutive daily partitions of p_table starting at p_from (alert when < 7, ADR-0089 §5).
CREATE FUNCTION infra.partition_days_ahead(p_table text, p_from date) RETURNS int
  LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, infra AS $$
DECLARE n int := 0;
BEGIN
  IF p_table NOT IN ('outbox_events', 'processed_events', 'dead_letters', 'idempotency_records') THEN
    RAISE EXCEPTION 'not an infra partitioned table: %', p_table;
  END IF;
  WHILE n < 62 AND to_regclass('infra.' || p_table || '_p' || to_char(p_from + n, 'YYYYMMDD')) IS NOT NULL LOOP
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;

-- Detach and drop daily partitions of p_table whose day is before p_before. Refuses (action 'refused') a
-- partition of outbox_events with unpublished rows or of dead_letters with unresolved rows. Never touches
-- the default partition nor any business table (ADR-0070 exception limited to these four tables).
CREATE FUNCTION infra.drop_expired_partitions(p_table text, p_before date)
  RETURNS TABLE (partition_name text, action text)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, infra AS $$
DECLARE r record; day date; blocked boolean;
BEGIN
  IF p_table NOT IN ('outbox_events', 'processed_events', 'dead_letters', 'idempotency_records') THEN
    RAISE EXCEPTION 'not an infra partitioned table: %', p_table;
  END IF;
  FOR r IN SELECT c.relname FROM pg_inherits i
             JOIN pg_class c ON c.oid = i.inhrelid
             JOIN pg_class p ON p.oid = i.inhparent
             JOIN pg_namespace n ON n.oid = p.relnamespace
            WHERE n.nspname = 'infra' AND p.relname = p_table AND c.relname ~ ('^' || p_table || '_p[0-9]{8}$')
            ORDER BY c.relname LOOP
    day := to_date(right(r.relname, 8), 'YYYYMMDD');
    CONTINUE WHEN day >= p_before;
    blocked := false;
    IF p_table = 'outbox_events' THEN
      EXECUTE format('SELECT EXISTS (SELECT 1 FROM infra.%I WHERE published_at IS NULL)', r.relname) INTO blocked;
    ELSIF p_table = 'dead_letters' THEN
      EXECUTE format('SELECT EXISTS (SELECT 1 FROM infra.%I WHERE resolved_at IS NULL)', r.relname) INTO blocked;
    END IF;
    IF blocked THEN
      partition_name := r.relname; action := 'refused'; RETURN NEXT;
      CONTINUE;
    END IF;
    EXECUTE format('ALTER TABLE infra.%I DETACH PARTITION infra.%I', p_table, r.relname);
    EXECUTE format('DROP TABLE infra.%I', r.relname);
    partition_name := r.relname; action := 'dropped'; RETURN NEXT;
  END LOOP;
END $$;

REVOKE ALL ON FUNCTION infra.ensure_partitions(date, int), infra.partition_days_ahead(text, date),
  infra.drop_expired_partitions(text, date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION infra.ensure_partitions(date, int), infra.partition_days_ahead(text, date),
  infra.drop_expired_partitions(text, date) TO [[.M]]_partition_admin;

-- First partitions: yesterday through the next 8 days (UTC).
SELECT infra.ensure_partitions((now() AT TIME ZONE 'UTC')::date - 1, 9);
`))
