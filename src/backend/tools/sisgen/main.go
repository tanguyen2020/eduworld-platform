// Command sisgen extracts the DTO schemas of the EduWorld SIS Contract (specs/sis/eduworld-sis-contract.v1.yaml,
// ADR-0021) into a JSON Schema 2020-12 document embedded by module identity: the CSV reader and the contract
// validator use it (F011 T001/T008), so the contract stays the single source of the columns and rules.
//
//	go run ./tools/sisgen           # write modules/identity/internal/infrastructure/sis/contract/contract.schema.json
//	go run ./tools/sisgen --check   # fail when the embedded schema differs from the contract
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"go.yaml.in/yaml/v3"
)

// Out is the embedded schema, relative to the Go module root.
const Out = "modules/identity/internal/infrastructure/sis/contract/contract.schema.json"

func main() {
	check := flag.Bool("check", false, "fail when the generated schema is stale")
	root := flag.String("root", ".", "Go module root (src/backend)")
	flag.Parse()
	want, err := Render(filepath.Join(*root, "..", "..", "specs", "sis", "eduworld-sis-contract.v1.yaml"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "sisgen:", err)
		os.Exit(1)
	}
	path := filepath.Join(*root, Out)
	if *check {
		cur, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(bytes.ReplaceAll(cur, []byte("\r\n"), []byte("\n")), want) {
			fmt.Fprintln(os.Stderr, "sisgen: stale", path, "(run go run ./tools/sisgen)")
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "sisgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "sisgen:", err)
		os.Exit(1)
	}
}

// Render returns the JSON Schema document of the contract DTOs ($defs = components.schemas).
func Render(contract string) ([]byte, error) {
	raw, err := os.ReadFile(contract)
	if err != nil {
		return nil, err
	}
	var doc struct {
		Info struct {
			Version string `yaml:"version"`
		} `yaml:"info"`
		Components struct {
			Schemas map[string]any `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("parse contract: %w", err)
	}
	if len(doc.Components.Schemas) == 0 {
		return nil, fmt.Errorf("contract has no components.schemas")
	}
	defs := rewrite(doc.Components.Schemas)
	out := map[string]any{
		"$schema":            "https://json-schema.org/draft/2020-12/schema",
		"$id":                "https://schemas.eduworld.vn/sis/contract.v1.json",
		"$comment":           "Code generated by tools/sisgen from specs/sis/eduworld-sis-contract.v1.yaml. DO NOT EDIT.",
		"x-contract-version": doc.Info.Version,
		"$defs":              defs,
	}
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// rewrite turns OpenAPI refs (#/components/schemas/X) into JSON Schema refs (#/$defs/X) recursively.
func rewrite(v any) any {
	switch t := v.(type) {
	case map[string]any:
		m := make(map[string]any, len(t))
		for k, x := range t {
			if k == "$ref" {
				if s, ok := x.(string); ok {
					m[k] = strings.Replace(s, "#/components/schemas/", "#/$defs/", 1)
					continue
				}
			}
			m[k] = rewrite(x)
		}
		return m
	case []any:
		out := make([]any, len(t))
		for i, x := range t {
			out[i] = rewrite(x)
		}
		return out
	default:
		return v
	}
}
