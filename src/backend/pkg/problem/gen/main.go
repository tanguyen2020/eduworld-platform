// Command gen writes pkg/problem/codes_gen.go from the single error catalog (F002 T004, F002-AC-21):
// codes from enum `ProblemCode` of specs/openapi/eduworld-api.v1.yaml, HTTP status from the tables of
// docs/07-backend/API_DESIGN.md §4.1. A code present on one side only is an error.
//
//	go run ./pkg/problem/gen            # from src/backend; `make gen` runs it
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	spec := flag.String("spec", "../../specs/openapi/eduworld-api.v1.yaml", "merged OpenAPI spec")
	doc := flag.String("doc", "../../docs/07-backend/API_DESIGN.md", "API_DESIGN.md (§4.1 tables)")
	out := flag.String("out", "pkg/problem/codes_gen.go", "output file")
	flag.Parse()
	if err := run(*spec, *doc, *out); err != nil {
		fmt.Fprintln(os.Stderr, "problem/gen:", err)
		os.Exit(1)
	}
}

func run(specPath, docPath, out string) error {
	codes, err := enumCodes(specPath)
	if err != nil {
		return err
	}
	md, err := os.ReadFile(docPath)
	if err != nil {
		return err
	}
	statuses, err := parseStatuses(string(md))
	if err != nil {
		return err
	}
	src, err := render(codes, statuses)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

func enumCodes(path string) ([]string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc struct {
		Components struct {
			Schemas struct {
				ProblemCode struct {
					Enum []string `yaml:"enum"`
				} `yaml:"ProblemCode"`
			} `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(doc.Components.Schemas.ProblemCode.Enum) == 0 {
		return nil, fmt.Errorf("%s: components.schemas.ProblemCode.enum not found", path)
	}
	return doc.Components.Schemas.ProblemCode.Enum, nil
}

var (
	rowRe  = regexp.MustCompile(`^\|\s*(\d{3})\s*\|([^|]*)\|`)
	codeRe = regexp.MustCompile("`([A-Z][A-Z0-9_]+)`")
)

// parseStatuses reads rows "| 403 | `CODE` [/ `CODE2`] | … |" inside "### 4.1." up to the next "## " heading.
func parseStatuses(md string) (map[string]int, error) {
	lines := strings.Split(md, "\n")
	start := -1
	for i, l := range lines {
		if strings.HasPrefix(l, "### 4.1.") {
			start = i
			break
		}
	}
	if start < 0 {
		return nil, fmt.Errorf("section ### 4.1. not found")
	}
	out := map[string]int{}
	for _, l := range lines[start+1:] {
		if strings.HasPrefix(l, "## ") {
			break
		}
		m := rowRe.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		status, _ := strconv.Atoi(m[1])
		for _, c := range codeRe.FindAllStringSubmatch(m[2], -1) {
			if prev, dup := out[c[1]]; dup && prev != status {
				return nil, fmt.Errorf("code %s listed with statuses %d and %d", c[1], prev, status)
			}
			out[c[1]] = status
		}
	}
	return out, nil
}

func render(codes []string, statuses map[string]int) ([]byte, error) {
	sorted := append([]string(nil), codes...)
	sort.Strings(sorted)
	var missing, extra []string
	inEnum := map[string]bool{}
	for _, c := range sorted {
		inEnum[c] = true
		if _, ok := statuses[c]; !ok {
			missing = append(missing, c)
		}
	}
	for c := range statuses {
		if !inEnum[c] {
			extra = append(extra, c)
		}
	}
	sort.Strings(extra)
	if len(missing) > 0 || len(extra) > 0 {
		return nil, fmt.Errorf("catalog mismatch: in ProblemCode without API_DESIGN §4.1 status %v; in §4.1 but not in ProblemCode %v", missing, extra)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by pkg/problem/gen from ProblemCode (specs/openapi/eduworld-api.v1.yaml) and API_DESIGN §4.1. DO NOT EDIT.\n\n")
	b.WriteString("package problem\n\n")
	b.WriteString("// Error codes of the single catalog (API_DESIGN §4.1).\nconst (\n")
	for _, c := range sorted {
		fmt.Fprintf(&b, "\t%s Code = %q\n", goName(c), c)
	}
	b.WriteString(")\n\nvar statusByCode = map[Code]int{\n")
	for _, c := range sorted {
		fmt.Fprintf(&b, "\t%s: %d,\n", goName(c), statuses[c])
	}
	b.WriteString("}\n\nvar allCodes = []Code{\n")
	for _, c := range sorted {
		fmt.Fprintf(&b, "\t%s,\n", goName(c))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// goName: TENANT_HEADER_REQUIRED → TenantHeaderRequired.
func goName(code string) string {
	parts := strings.Split(strings.ToLower(code), "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}
