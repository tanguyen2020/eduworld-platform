// Command seed-media loads the DEV-ONLY media lessons of LOCAL_DEVELOPMENT §5 (`make seed-media`, after
// `make seed-content`): it generates SYNTHETIC clips (ffmpeg test pattern + sine tone) in a throwaway container of the
// media-tools image (never committed, never written to the repository), uploads them with the WebVTT subtitles of
// seed/media through the real media pipeline of the CMS (presign → PUT → complete-upload → worker transcode, F027),
// publishes the video_lesson, audio_lesson and simulation activities of seed/content/media_g3.dev.json through the CMS
// workflow — tenant content of th-demo-a (platform media cannot be assigned to a tenant yet) — and has ad.truong.a give
// them to DEMOA1 khối 3
// (seed/assignments/demoa1_g3_media.dev.json). Running it again uploads, creates and publishes nothing: media is found by
// file name (and the generated bytes are deterministic, so the sha256 dedup of F027 applies too).
//
// Configuration (no default URL in code, AGENTS R3): EW_SEED_API_URL, EW_SEED_INTERNAL_API_URL, EW_SEED_PASSWORD (demo
// password, never logged), EW_ENV=local, EW_SEED_MEDIA_IMAGE (image with ffmpeg, e.g. eduworld/worker:local),
// EW_SEED_S3_ADDR (optional host:port the presigned PUT is sent to, e.g. localhost:4566 when the URL names floci:4566).
package main

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"sort"
	"strings"
	"syscall"
	"time"

	"github.com/tanguyen2020/eduworld-platform/src/backend/modules/learning/internal/presentation/devseed"
)

func main() {
	lessons := flag.String("lessons", filepath.Join("modules", "learning", "seed", "content", "media_g3.dev.json"), "DEV media lesson file")
	assignments := flag.String("assignments", filepath.Join("modules", "learning", "seed", "assignments", "demoa1_g3_media.dev.json"),
		"DEV school assignment file of the media lessons (empty = skip)")
	wait := flag.Duration("wait", 15*time.Minute, "how long to wait for the media worker per asset")
	flag.Parse()
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, *lessons, *assignments, *wait); err != nil {
		slog.Error("learning media seed failed", "error", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, lessonsPath, assignmentsPath string, wait time.Duration) error {
	if os.Getenv("EW_ENV") != "local" {
		return errors.New("seed-media is a local dev seed: EW_ENV must be local")
	}
	vals := map[string]string{}
	for _, k := range []string{"EW_SEED_API_URL", "EW_SEED_INTERNAL_API_URL", "EW_SEED_PASSWORD", "EW_SEED_MEDIA_IMAGE"} {
		v, err := devseed.Env(k)
		if err != nil {
			return err
		}
		vals[k] = v
	}
	api, internal, pw := vals["EW_SEED_API_URL"], vals["EW_SEED_INTERNAL_API_URL"], vals["EW_SEED_PASSWORD"]
	var lf devseed.LessonFile
	if err := devseed.LoadJSON(lessonsPath, &lf); err != nil {
		return err
	}
	var af devseed.AssignmentFile
	if assignmentsPath != "" {
		if err := devseed.LoadJSON(assignmentsPath, &af); err != nil {
			return err
		}
	}
	hc := &http.Client{Timeout: 2 * time.Minute}
	login := func(u string) (string, error) { return devseed.PortalLogin(ctx, hc, api, u, pw) }
	wd, err := os.Getwd()
	if err != nil {
		return err
	}
	// Media is uploaded by System Admin: the only seeded user with media.upload (content_admin, academic_manager and
	// school_admin have none). It is made ready first — the worker may take minutes, longer than a portal access token
	// lives — then the content staff sign in.
	admin, err := login("sa.admin")
	if err != nil {
		return err
	}
	// Tenant content (owner_tenant_code): authored by the academic manager of the tenant, reviewed by System Admin in that
	// tenant (reviewer ≠ author), media of the tenant, nothing to assign. Platform content: the authors of seed-content.
	authorName, reviewerName, tenantID := "cm.noidung", "cm.duyet", ""
	if lf.OwnerTenantCode != "" {
		ids, err := (&devseed.AdminAssigner{HTTP: hc, BaseURL: internal, Token: admin, Codes: []string{lf.OwnerTenantCode}}).Tenants(ctx)
		if err != nil {
			return err
		}
		authorName, reviewerName, tenantID = "qlcm.truong.a", "sa.admin", ids[0]
	}
	mc := &devseed.MediaClient{BaseURL: api, HTTP: hc, Token: admin, RepoDir: wd, Wait: wait, TenantID: tenantID,
		Generator: docker{image: vals["EW_SEED_MEDIA_IMAGE"]}, S3Addr: strings.TrimSpace(os.Getenv("EW_SEED_S3_ADDR")),
		Relogin: func(context.Context) (string, error) { return login("sa.admin") }}
	uploaded := 0
	for _, m := range lf.Media {
		_, up, err := mc.Ensure(ctx, m)
		if err != nil {
			return fmt.Errorf("media %s: %w", m.Key, err)
		}
		if up {
			uploaded++
		}
	}
	if admin, err = login("sa.admin"); err != nil {
		return err
	}
	mc.Token = admin
	author, err := login(authorName)
	if err != nil {
		return err
	}
	reviewer, err := login(reviewerName)
	if err != nil {
		return err
	}
	cl := devseed.Client{BaseURL: api, HTTP: hc, Author: author, Reviewer: reviewer, ActivityReviewer: admin}
	var assigner devseed.Assigner
	if tenantID != "" {
		cl.Headers, cl.OwnerScope = map[string]string{"X-Tenant-Id": tenantID}, "tenant"
	} else {
		assigner = &devseed.AdminAssigner{HTTP: hc, BaseURL: internal, Token: admin, Codes: lf.TenantCodes}
	}
	res, err := devseed.RunLessons(ctx, cl, mc, assigner, lf)
	if err != nil {
		return err
	}
	res.Uploaded += uploaded
	logResult(ctx, res)
	if assignmentsPath == "" {
		return nil
	}
	schoolAdmin, err := login(af.Author)
	if err != nil {
		return err
	}
	ar, err := devseed.RunAssignments(ctx, devseed.AssignmentClient{BaseURL: api, HTTP: hc, Token: schoolAdmin},
		&devseed.AdminAssigner{HTTP: hc, BaseURL: internal, Token: admin, Codes: []string{af.TenantCode}}, af,
		devseed.Result{SubjectID: res.SubjectID, Activities: res.Activities})
	if err != nil {
		return err
	}
	slog.InfoContext(ctx, "learning media assignment seed done", "tenant", af.TenantCode, "school", af.SchoolCode,
		"assignments", len(ar.Assignments), "created_now", ar.Created, "published_now", ar.Published)
	return nil
}

func logResult(ctx context.Context, res devseed.LessonResult) {
	keys := make([]string, 0, len(res.Activities))
	for k := range res.Activities {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		slog.InfoContext(ctx, "seeded activity", "key", k, "activity_id", res.Activities[k])
	}
	for k, id := range res.Media {
		slog.InfoContext(ctx, "seeded media", "key", k, "asset_id", id)
	}
	slog.InfoContext(ctx, "learning media seed done", "media", len(res.Media), "uploaded_now", res.Uploaded, "questions", len(res.Questions),
		"activities", len(res.Activities), "published_now", res.Published)
}

// docker generates a synthetic clip with ffmpeg inside a throwaway container of the media-tools image (lavfi test
// pattern + sine tone, single-threaded bit-exact encoding: the same file every run). The clip only lives in memory.
type docker struct{ image string }

func (d docker) Generate(ctx context.Context, kind string, g devseed.MediaGenerate) ([]byte, error) {
	var script string
	switch kind {
	case "video":
		script = fmt.Sprintf("ffmpeg -nostdin -hide_banner -loglevel error -f lavfi -i testsrc2=size=%dx%d:rate=%d:duration=%d "+
			"-f lavfi -i sine=frequency=%d:sample_rate=22050:duration=%d -map_metadata -1 -fflags +bitexact -flags:v +bitexact "+
			"-flags:a +bitexact -c:v libx264 -preset veryfast -crf 32 -pix_fmt yuv420p -threads 1 -c:a aac -b:a 48k -ac 1 -shortest "+
			"-movflags +faststart /tmp/clip.mp4 && cat /tmp/clip.mp4", g.Width, g.Height, g.FPS, g.DurationS, g.ToneHz, g.DurationS)
	case "audio":
		script = fmt.Sprintf("ffmpeg -nostdin -hide_banner -loglevel error -f lavfi -i sine=frequency=%d:sample_rate=22050:duration=%d "+
			"-map_metadata -1 -fflags +bitexact -flags:a +bitexact -c:a libvorbis -q:a 2 -ac 1 /tmp/clip.ogg && cat /tmp/clip.ogg",
			g.ToneHz, g.DurationS)
	default:
		return nil, fmt.Errorf("cannot generate %s", kind)
	}
	ctx, cancel := context.WithTimeout(ctx, 10*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "docker", "run", "--rm", "--network", "none", "--entrypoint", "sh", d.image, "-c", script) //nolint:gosec // fixed image of the env, numeric arguments only
	var out, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &stderr
	start := time.Now()
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("generate %s with %s: %w: %s", kind, d.image, err, strings.TrimSpace(stderr.String()))
	}
	slog.InfoContext(ctx, "synthetic media generated", "kind", kind, "bytes", out.Len(), "took", time.Since(start).Round(time.Second))
	return out.Bytes(), nil
}
